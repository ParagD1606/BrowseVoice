export function getUiTranslation(key: string, language: SupportedLanguageCode, fallback?: string): string {
  const entry = UI_TRANSLATIONS[key];
  if (entry && entry[language]) {
    return entry[language];
  }
  if (language === "hi-IN" && fallback) {
    return fallback;
  }
  return entry?.["en-IN"] || fallback || key;
}
