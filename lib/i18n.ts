export type SupportedLanguageCode =
  | "en-IN"
  | "hi-IN"
  | "ta-IN"
  | "te-IN"
  | "kn-IN"
  | "mr-IN"
  | "gu-IN"
  | "bn-IN"
  | "pa-IN"
  | "ml-IN";

export type InterfaceLanguage = SupportedLanguageCode | "indic-auto";

export function resolveLanguage(code: string, text: string = ""): SupportedLanguageCode {
  const normalized = (code || "").trim().toLowerCase();
  if (normalized && normalized !== "indic-auto") {
    if (code === "en-IN" || code === "hi-IN" || code === "ta-IN" || code === "te-IN" ||
        code === "kn-IN" || code === "mr-IN" || code === "gu-IN" || code === "bn-IN" ||
        code === "pa-IN" || code === "ml-IN") {
      return code;
    }
    const nameMap: Record<string, SupportedLanguageCode> = {
      hindi: "hi-IN",
      tamil: "ta-IN",
      telugu: "te-IN",
      kannada: "kn-IN",
      marathi: "mr-IN",
      gujarati: "gu-IN",
      bengali: "bn-IN",
      punjabi: "pa-IN",
      malayalam: "ml-IN",
      english: "en-IN",
    };
    if (nameMap[normalized]) {
      return nameMap[normalized];
    }
    const prefix = normalized.split(/[-_]/)[0];
    const prefixMap: Record<string, SupportedLanguageCode> = {
      hi: "hi-IN",
      ta: "ta-IN",
      te: "te-IN",
      kn: "kn-IN",
      mr: "mr-IN",
      gu: "gu-IN",
      bn: "bn-IN",
      pa: "pa-IN",
      ml: "ml-IN",
      en: "en-IN",
    };
    if (prefixMap[prefix]) {
      return prefixMap[prefix];
    }
    return "en-IN";
  }
  if (/\p{Script=Tamil}/u.test(text)) return "ta-IN";
  if (/\p{Script=Telugu}/u.test(text)) return "te-IN";
  if (/\p{Script=Kannada}/u.test(text)) return "kn-IN";
  if (/\p{Script=Bengali}/u.test(text)) return "bn-IN";
  if (/\p{Script=Gurmukhi}/u.test(text)) return "pa-IN";
  if (/\p{Script=Malayalam}/u.test(text)) return "ml-IN";
  if (/\p{Script=Gujarati}/u.test(text)) return "gu-IN";
  if (/\p{Script=Devanagari}/u.test(text)) return "hi-IN";
  return "hi-IN";
}

